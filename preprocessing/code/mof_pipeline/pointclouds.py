GRID_THRESHOLD = 13_000_000
DENSITY_THRESHOLDS = (0.02, 0.03, 0.05, 0.08, 0.10)
SURFACE_TARGETS = (0.001, 0.002, 0.003)
SURFACE_WINDOW = 0.0002
TAIL_FRACTIONS = (0.03, 0.05, 0.07)


def factor_for_points(points: int) -> float:
    if points <= GRID_THRESHOLD:
        return 1.0
    if points <= 25_000_000:
        return 1.25
    if points <= 50_000_000:
        return 1.5
    return 2.0


def target_shape(shape: tuple[int, int, int], factor: float) -> tuple[int, int, int]:
    return tuple(max(1, int(round(value / factor))) for value in shape)


def selected_xyz(
    flat_indices: np.ndarray,
    shape: tuple[int, int, int],
    origin: np.ndarray,
    lattice: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    ny, nz = shape[1], shape[2]
    i = flat_indices // (ny * nz)
    rem = flat_indices % (ny * nz)
    j = rem // nz
    k = rem % nz
    frac = np.empty((flat_indices.size, 3), dtype=np.float32)
    frac[:, 0] = i / shape[0]
    frac[:, 1] = j / shape[1]
    frac[:, 2] = k / shape[2]
    xyz = (
        origin.astype(np.float32)[None, :]
        + frac[:, 0, None] * lattice[0].astype(np.float32)
        + frac[:, 1, None] * lattice[1].astype(np.float32)
        + frac[:, 2, None] * lattice[2].astype(np.float32)
    )
    return xyz.astype(np.float32, copy=False), frac


def write_binary_ply(
    path: Path,
    columns: list[tuple[str, np.ndarray, str, str]],
    chunk_size: int = 500_000,
) -> None:
    """Write little-endian binary PLY.

    Each column is (name, values, PLY type, NumPy dtype).
    """
    count = len(columns[0][1]) if columns else 0
    if any(len(values) != count for _, values, _, _ in columns):
        raise ValueError("PLY columns have different lengths")
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    dtype = np.dtype([(name, np_dtype) for name, _, _, np_dtype in columns])
    header = [
        "ply",
        "format binary_little_endian 1.0",
        "comment generated by build_cp3d_point_clouds_gt13m.py",
        f"element vertex {count}",
        *[f"property {ply_type} {name}" for name, _, ply_type, _ in columns],
        "end_header",
        "",
    ]
    with tmp.open("wb") as handle:
        handle.write("\n".join(header).encode("ascii"))
        for start in range(0, count, chunk_size):
            stop = min(count, start + chunk_size)
            records = np.empty(stop - start, dtype=dtype)
            for name, values, _, _ in columns:
                records[name] = values[start:stop]
            records.tofile(handle)
    os.replace(tmp, path)


def geometry(metadata: dict[str, object], shape: tuple[int, int, int]) -> tuple[np.ndarray, np.ndarray]:
    origin = np.asarray(metadata["origin"], dtype=np.float64)
    axes = np.asarray(metadata["axes"], dtype=np.float64)
    lattice = axes * np.asarray(shape, dtype=np.float64)[:, None]
    return origin, lattice


def write_density_clouds(
    output_dir: Path,
    density: np.ndarray,
    origin: np.ndarray,
    lattice: np.ndarray,
    thresholds: tuple[float, ...] = DENSITY_THRESHOLDS,
) -> list[dict[str, object]]:
    outputs: list[dict[str, object]] = []
    flat_density = density.ravel()
    for threshold in thresholds:
        indices = np.flatnonzero((density >= threshold).ravel())
        xyz, frac = selected_xyz(indices, density.shape, origin, lattice)
        rho = flat_density[indices].astype(np.float32, copy=False)
        path = output_dir / f"density_gt_{threshold:g}.ply"
        write_binary_ply(
            path,
            [
                ("x", xyz[:, 0], "float", "<f4"),
                ("y", xyz[:, 1], "float", "<f4"),
                ("z", xyz[:, 2], "float", "<f4"),
                ("density", rho, "float", "<f4"),
                ("frac_x", frac[:, 0], "float", "<f4"),
                ("frac_y", frac[:, 1], "float", "<f4"),
                ("frac_z", frac[:, 2], "float", "<f4"),
            ],
        )
        outputs.append(
            {"threshold": threshold, "file": str(path), "points": int(indices.size)}
        )
    return outputs


def write_surface_clouds(
    output_dir: Path,
    material: str,
    density: np.ndarray,
    esp: np.ndarray,
    origin: np.ndarray,
    lattice: np.ndarray,
) -> list[dict[str, object]]:
    outputs: list[dict[str, object]] = []
    flat_rho = density.ravel()
    flat_esp = esp.ravel()
    for target in SURFACE_TARGETS:
        indices = np.flatnonzero((np.abs(density - target) <= SURFACE_WINDOW).ravel())
        xyz, frac = selected_xyz(indices, density.shape, origin, lattice)
        rho = flat_rho[indices].astype(np.float32, copy=False)
        potential = flat_esp[indices].astype(np.float32, copy=False)
        tag = f"{target:.3f}".replace(".", "p")
        path = output_dir / f"esp_on_density_{target:g}_pm_{SURFACE_WINDOW:g}.ply"
        write_binary_ply(
            path,
            [
                ("x", xyz[:, 0], "float", "<f4"),
                ("y", xyz[:, 1], "float", "<f4"),
                ("z", xyz[:, 2], "float", "<f4"),
                ("esp", potential, "float", "<f4"),
                ("rho", rho, "float", "<f4"),
                ("frac_x", frac[:, 0], "float", "<f4"),
                ("frac_y", frac[:, 1], "float", "<f4"),
                ("frac_z", frac[:, 2], "float", "<f4"),
            ],
        )
        outputs.append({"target": target, "window": SURFACE_WINDOW, "file": str(path), "points": int(indices.size)})
    return outputs


def write_tail_clouds(
    output_dir: Path,
    esp: np.ndarray,
    origin: np.ndarray,
    lattice: np.ndarray,
    tail_fractions: tuple[float, ...] = TAIL_FRACTIONS,
) -> list[dict[str, object]]:
    fractions = np.asarray(tail_fractions)
    quantiles = np.quantile(
        esp,
        np.concatenate([fractions, 1.0 - fractions]),
    )
    lows = quantiles[: len(fractions)]
    highs = quantiles[len(fractions) :]
    flat_esp = esp.ravel()
    outputs: list[dict[str, object]] = []
    for fraction, low, high in zip(fractions, lows, highs):
        percent = int(round(fraction * 100))
        for tail_name, mask, threshold in (
            ("lowest", esp <= low, low),
            ("highest", esp >= high, high),
        ):
            indices = np.flatnonzero(mask.ravel())
            values = flat_esp[indices].astype(np.float32, copy=False)
            xyz, frac = selected_xyz(indices, esp.shape, origin, lattice)
            path = output_dir / f"esp_{tail_name}_{percent}pct.ply"
            write_binary_ply(
                path,
                [
                    ("x", xyz[:, 0], "float", "<f4"),
                    ("y", xyz[:, 1], "float", "<f4"),
                    ("z", xyz[:, 2], "float", "<f4"),
                    ("esp", values, "float", "<f4"),
                    ("frac_x", frac[:, 0], "float", "<f4"),
                    ("frac_y", frac[:, 1], "float", "<f4"),
                    ("frac_z", frac[:, 2], "float", "<f4"),
                ],
            )
            outputs.append(
                {
                    "tail": tail_name,
                    "percent": percent,
                    "threshold": float(threshold),
                    "file": str(path),
                    "points": int(indices.size),
                }
            )
    return outputs


def find_field(material_dir: Path, pattern: str) -> Path | None:
    matches = sorted(material_dir.glob(pattern))
    if not matches:
        return None
    if len(matches) != 1:
        raise ValueError(f"{material_dir}: expected at most one {pattern}, got {len(matches)}")
    return matches[0]

